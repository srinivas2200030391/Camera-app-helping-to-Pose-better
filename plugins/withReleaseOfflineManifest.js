/**
 * Config plugin: strip network permissions from *release* builds only.
 *
 * PoseLens AI processes photos entirely on-device. Removing INTERNET from the release
 * manifest makes that guarantee verifiable (`aapt dump permissions app.apk`), while debug /
 * development-client builds keep INTERNET so they can reach the Metro dev server.
 *
 * Writes android/app/src/release/AndroidManifest.xml, which the Android manifest merger
 * applies on top of the main manifest and every library manifest for the release variant.
 */
const fs = require('fs');
const path = require('path');
const { withDangerousMod } = require('expo/config-plugins');

const REMOVED_PERMISSIONS = [
  'android.permission.INTERNET',
  'android.permission.ACCESS_NETWORK_STATE',
  'android.permission.ACCESS_WIFI_STATE',
  // Only the dev client's overlay needs this; release builds never draw over other apps.
  'android.permission.SYSTEM_ALERT_WINDOW',
];

function buildManifest() {
  const lines = REMOVED_PERMISSIONS.map(
    (permission) => `    <uses-permission android:name="${permission}" tools:node="remove" />`,
  );
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<!-- Generated by plugins/withReleaseOfflineManifest.js. Do not edit by hand. -->',
    '<manifest xmlns:android="http://schemas.android.com/apk/res/android"',
    '    xmlns:tools="http://schemas.android.com/tools">',
    ...lines,
    '</manifest>',
    '',
  ].join('\n');
}

module.exports = function withReleaseOfflineManifest(config) {
  return withDangerousMod(config, [
    'android',
    async (modConfig) => {
      const releaseDir = path.join(modConfig.modRequest.platformProjectRoot, 'app', 'src', 'release');
      await fs.promises.mkdir(releaseDir, { recursive: true });
      await fs.promises.writeFile(path.join(releaseDir, 'AndroidManifest.xml'), buildManifest());
      return modConfig;
    },
  ]);
};
