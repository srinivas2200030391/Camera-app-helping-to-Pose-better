let cache: Pose[] | null = null;

export function getPoses(): readonly Pose[] {
  cache ??= DEFINITIONS.map((definition) => ({ ...definition, figures: definition.figures.map(buildFigure) }));
  return cache;
}

export function getPose(id: string): Pose | undefined {
  return getPoses().find((pose) => pose.id === id);
}

export function posesInCategory(category: PoseCategoryId): Pose[] {
  return getPoses().filter((pose) => pose.categories.includes(category));
}

export function searchPoses(query: string): Pose[] {
  const q = query.trim().toLowerCase();
  if (!q) return [...getPoses()];
  return getPoses().filter(
    (pose) =>
      pose.name.toLowerCase().includes(q) ||
      pose.categories.some((category) => category.includes(q)) ||
      pose.instructions.some((step) => step.toLowerCase().includes(q)),
  );
}
